  Future<void> joinGame(String gameId) async {
    final gameRef =
        FirebaseFirestore.instance.collection('stranger_games').doc(gameId);

    // Add the current user to the players array if not already present
    await gameRef.update({
      'players': FieldValue.arrayUnion([currentUserUid]),
    });
  }

  Future<void> startGame(String gameId) async {
    final gameRef =
        FirebaseFirestore.instance.collection('stranger_games').doc(gameId);
    final gameDoc = await gameRef.get();

    if (!gameDoc.exists) {
      throw Exception('Game not found');
    }

    final data = gameDoc.data() as Map<String, dynamic>;
    final players = List<String>.from(data['players'] ?? []);
    final readyPlayers = List<String>.from(data['readyPlayers'] ?? []);
    final creatorId = data['creatorId'];

    if (currentUserUid != creatorId) {
      throw Exception('Only the creator can start the game');
    }

    if (players.length < 2) {
      throw Exception('Not enough players to start the game');
    }

    if (readyPlayers.length != players.length) {
      throw Exception('All players must be ready to start the game');
    }

    // Randomly select a stranger from the players
    players.shuffle();
    final strangerId = players.first;

    // Select a random category and topic
    final categories = categoriesAndTopics.keys.toList();
    categories.shuffle();
    final selectedCategory = categories.first;

    final topics = categoriesAndTopics[selectedCategory]!;
    topics.shuffle();
    final selectedTopic = topics.first;

    // Update the game with the selected stranger, category, and topic
    await gameRef.update({
      'isStarted': true,
      'strangerId': strangerId,
      'category': selectedCategory,
      'topic': selectedTopic,
      'startedAt': FieldValue.serverTimestamp(),
    });
  }

  Future<Map<String, dynamic>> getGameStatus(String gameId) async {
    final gameDoc = await FirebaseFirestore.instance
        .collection('stranger_games')
        .doc(gameId)
        .get();

    if (!gameDoc.exists) {
      return {
        'isStarted': false,
        'isStranger': false,
        'topic': null,
        'category': null,
      };
    }

    final data = gameDoc.data() as Map<String, dynamic>;
    return {
      'isStarted': data['isStarted'] ?? false,
      'isStranger': data['strangerId'] == currentUserUid,
      'topic': data['topic'],
      'category': data['category'],
    };
  }
